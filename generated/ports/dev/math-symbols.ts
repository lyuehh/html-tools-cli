      let currentCategory = "all";
      let searchQuery = "";

      function init() {
        renderCategoryTabs();
        renderSymbols();

        const savedTheme = localStorage.getItem("math-symbols-theme");
        if (savedTheme) {
          document.documentElement.setAttribute("data-theme", savedTheme);
        } else if (window.matchMedia("(prefers-color-scheme: dark)").matches) {
          document.documentElement.setAttribute("data-theme", "dark");
        }
      }

      function renderCategoryTabs() {
        const container = document.getElementById("categoryTabs");
        while (container.firstChild) {
          container.removeChild(container.firstChild);
        }

        const allTab = document.createElement("button");
        allTab.className = "category-tab" + (currentCategory === "all" ? " active" : "");
        allTab.textContent = "全部";
        allTab.onclick = function () {
          selectCategory("all");
        };
        container.appendChild(allTab);

        Object.keys(mathSymbols).forEach(function (category) {
          const tab = document.createElement("button");
          tab.className = "category-tab" + (currentCategory === category ? " active" : "");
          tab.textContent = category;
          tab.onclick = function () {
            selectCategory(category);
          };
          container.appendChild(tab);
        });
      }

      function selectCategory(category) {
        currentCategory = category;
        renderCategoryTabs();
        renderSymbols();
      }

      function renderSymbols() {
        const content = document.getElementById("symbolContent");
        const stats = document.getElementById("stats");

        while (content.firstChild) {
          content.removeChild(content.firstChild);
        }

        let totalCount = 0;
        const categories = currentCategory === "all" ? Object.keys(mathSymbols) : [currentCategory];

        categories.forEach(function (categoryName) {
          if (!mathSymbols[categoryName]) return;

          let items = mathSymbols[categoryName];

          if (searchQuery) {
            const query = searchQuery.toLowerCase();
            items = items.filter(function (item) {
              return (
                item.name.toLowerCase().includes(query) ||
                item.latex.toLowerCase().includes(query) ||
                item.char.includes(query)
              );
            });
          }

          if (items.length === 0) return;

          if (currentCategory === "all") {
            const title = document.createElement("h3");
            title.className = "section-title";
            title.textContent = categoryName;
            content.appendChild(title);
          }

          const table = document.createElement("table");
          table.className = "symbol-table";

          const thead = document.createElement("thead");
          const headerRow = document.createElement("tr");
          ["符号", "名称", "LaTeX", "HTML"].forEach(function (text) {
            const th = document.createElement("th");
            th.textContent = text;
            headerRow.appendChild(th);
          });
          thead.appendChild(headerRow);
          table.appendChild(thead);

          const tbody = document.createElement("tbody");

          items.forEach(function (item) {
            const row = document.createElement("tr");

            const charCell = document.createElement("td");
            charCell.className = "symbol-char";
            charCell.textContent = item.char;
            charCell.title = "点击复制符号";
            charCell.onclick = function () {
              copyText(item.char, "符号");
            };

            const nameCell = document.createElement("td");
            nameCell.textContent = item.name;

            const latexCell = document.createElement("td");
            const latexSpan = document.createElement("span");
            latexSpan.className = "symbol-latex";
            latexSpan.textContent = item.latex;
            latexSpan.title = "点击复制LaTeX";
            latexSpan.onclick = function () {
              copyText(item.latex, "LaTeX");
            };
            latexCell.appendChild(latexSpan);

            const htmlCell = document.createElement("td");
            htmlCell.className = "symbol-html";
            htmlCell.textContent = item.html || "-";

            row.appendChild(charCell);
            row.appendChild(nameCell);
            row.appendChild(latexCell);
            row.appendChild(htmlCell);
            tbody.appendChild(row);
            totalCount++;
          });

          table.appendChild(tbody);
          content.appendChild(table);
        });

        if (totalCount === 0) {
          const noResults = document.createElement("div");
          noResults.className = "no-results";
          noResults.textContent = "没有找到匹配的符号";
          content.appendChild(noResults);
        }

        stats.textContent = "共 " + totalCount + " 个符号";
      }

      window.filterSymbols = function () {
        searchQuery = document.getElementById("searchInput").value;
        renderSymbols();
      };

      window.copyText = function (text, type) {
        navigator.clipboard.writeText(text).then(function () {
          showToast("已复制" + type + ": " + text);
        });
      };

      function showToast(message) {
        const toast = document.getElementById("toast");
        toast.textContent = message;
        toast.classList.add("show");
        setTimeout(function () {
          toast.classList.remove("show");
        }, 2000);
      }

      window.toggleTheme = function () {
        const html = document.documentElement;
        const currentTheme = html.getAttribute("data-theme");
        const newTheme = currentTheme === "dark" ? "light" : "dark";
        html.setAttribute("data-theme", newTheme);
        localStorage.setItem("math-symbols-theme", newTheme);
      };

