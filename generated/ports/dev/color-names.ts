      function init() {
        renderCategoryTabs();
        renderColors();

        const savedTheme = localStorage.getItem("color-names-theme");
        if (savedTheme) {
          document.documentElement.setAttribute("data-theme", savedTheme);
        } else if (window.matchMedia("(prefers-color-scheme: dark)").matches) {
          document.documentElement.setAttribute("data-theme", "dark");
        }
      }

      function renderCategoryTabs() {
        const container = document.getElementById("categoryTabs");
        while (container.firstChild) {
          container.removeChild(container.firstChild);
        }

        const allTab = document.createElement("button");
        allTab.className = "category-tab" + (currentCategory === "all" ? " active" : "");
        allTab.textContent = "全部";
        allTab.onclick = function () {
          selectCategory("all");
        };
        container.appendChild(allTab);

        Object.keys(cssColors).forEach(function (category) {
          const tab = document.createElement("button");
          tab.className = "category-tab" + (currentCategory === category ? " active" : "");
          tab.textContent = category;
          tab.onclick = function () {
            selectCategory(category);
          };
          container.appendChild(tab);
        });
      }

      function selectCategory(category) {
        currentCategory = category;
        renderCategoryTabs();
        renderColors();
      }

      function getAllColors() {
        const colors = [];
        Object.keys(cssColors).forEach(function (category) {
          Object.keys(cssColors[category]).forEach(function (name) {
            colors.push({
              name: name,
              hex: cssColors[category][name],
              category: category
            });
          });
        });
        return colors;
      }

      function hexToRgb(hex) {
        const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
        return result
          ? {
              r: parseInt(result[1], 16),
              g: parseInt(result[2], 16),
              b: parseInt(result[3], 16)
            }
          : null;
      }

      function rgbToHsl(r, g, b) {
        r /= 255;
        g /= 255;
        b /= 255;
        const max = Math.max(r, g, b);
        const min = Math.min(r, g, b);
        let h,
          s,
          l = (max + min) / 2;

        if (max === min) {
          h = s = 0;
        } else {
          const d = max - min;
          s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
          switch (max) {
            case r:
              h = ((g - b) / d + (g < b ? 6 : 0)) / 6;
              break;
            case g:
              h = ((b - r) / d + 2) / 6;
              break;
            case b:
              h = ((r - g) / d + 4) / 6;
              break;
          }
        }
        return { h: h * 360, s: s * 100, l: l * 100 };
      }

      function getContrastColor(hex) {
        const rgb = hexToRgb(hex);
        const luminance = (0.299 * rgb.r + 0.587 * rgb.g + 0.114 * rgb.b) / 255;
        return luminance > 0.5 ? "#000000" : "#FFFFFF";
      }

      function renderColors() {
        const grid = document.getElementById("colorGrid");
        const stats = document.getElementById("stats");

        while (grid.firstChild) {
          grid.removeChild(grid.firstChild);
        }

        let colors = getAllColors();

        if (currentCategory !== "all") {
          colors = colors.filter(function (c) {
            return c.category === currentCategory;
          });
        }

        if (searchQuery) {
          const query = searchQuery.toLowerCase();
          colors = colors.filter(function (c) {
            return c.name.toLowerCase().includes(query) || c.hex.toLowerCase().includes(query);
          });
        }

        const sortBy = document.getElementById("sortSelect").value;
        colors.sort(function (a, b) {
          if (sortBy === "name") {
            return a.name.localeCompare(b.name);
          } else if (sortBy === "hue") {
            const rgbA = hexToRgb(a.hex);
            const rgbB = hexToRgb(b.hex);
            const hslA = rgbToHsl(rgbA.r, rgbA.g, rgbA.b);
            const hslB = rgbToHsl(rgbB.r, rgbB.g, rgbB.b);
            return hslA.h - hslB.h;
          } else if (sortBy === "lightness") {
            const rgbA = hexToRgb(a.hex);
            const rgbB = hexToRgb(b.hex);
            const hslA = rgbToHsl(rgbA.r, rgbA.g, rgbA.b);
            const hslB = rgbToHsl(rgbB.r, rgbB.g, rgbB.b);
            return hslB.l - hslA.l;
          }
          return 0;
        });

        stats.textContent = "显示 " + colors.length + " 种颜色";

        if (colors.length === 0) {
          const noResults = document.createElement("div");
          noResults.className = "no-results";
          noResults.textContent = "没有找到匹配的颜色";
          grid.appendChild(noResults);
          return;
        }

        colors.forEach(function (color) {
          const rgb = hexToRgb(color.hex);
          const card = document.createElement("div");
          card.className = "color-card";
          card.onclick = function () {
            copyColor(color.name, color.hex);
          };

          const preview = document.createElement("div");
          preview.className = "color-preview";
          preview.style.backgroundColor = color.hex;
          preview.style.color = getContrastColor(color.hex);
          preview.textContent = "点击复制";

          const info = document.createElement("div");
          info.className = "color-info";

          const nameEl = document.createElement("div");
          nameEl.className = "color-name";
          nameEl.textContent = color.name;

          const hexEl = document.createElement("div");
          hexEl.className = "color-hex";
          hexEl.textContent = color.hex;

          const rgbEl = document.createElement("div");
          rgbEl.className = "color-rgb";
          rgbEl.textContent = "rgb(" + rgb.r + ", " + rgb.g + ", " + rgb.b + ")";

          info.appendChild(nameEl);
          info.appendChild(hexEl);
          info.appendChild(rgbEl);

          card.appendChild(preview);
          card.appendChild(info);
          grid.appendChild(card);
        });
      }

      window.filterColors = function () {
        searchQuery = document.getElementById("searchInput").value;
        renderColors();
      };

      window.copyColor = function (name, hex) {
        const text = name + "\n" + hex;
        navigator.clipboard.writeText(text).then(function () {
          showToast("已复制: " + name + " " + hex);
        });
      };

      function showToast(message) {
        const toast = document.getElementById("toast");
        toast.textContent = message;
        toast.classList.add("show");
        setTimeout(function () {
          toast.classList.remove("show");
        }, 2000);
      }

      window.toggleTheme = function () {
        const html = document.documentElement;
        const currentTheme = html.getAttribute("data-theme");
        const newTheme = currentTheme === "dark" ? "light" : "dark";
        html.setAttribute("data-theme", newTheme);
        localStorage.setItem("color-names-theme", newTheme);
      };

