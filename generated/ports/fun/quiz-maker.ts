      let currentCategory = "general";
      let currentDifficulty = "easy";
      let currentQuestions = [];
      let currentIndex = 0;
      let score = 0;
      let timer = null;
      let timeLeft = 30;
      let totalTime = 0;
      let answered = false;

      // Event listeners
      document.querySelectorAll(".category-btn").forEach((btn) => {
        btn.onclick = () => {
          document.querySelectorAll(".category-btn").forEach((b) => b.classList.remove("active"));
          btn.classList.add("active");
          currentCategory = btn.dataset.category;
        };
      });

      document.querySelectorAll(".diff-btn").forEach((btn) => {
        btn.onclick = () => {
          document.querySelectorAll(".diff-btn").forEach((b) => b.classList.remove("active"));
          btn.classList.add("active");
          currentDifficulty = btn.dataset.diff;
        };
      });

      function startQuiz() {
        currentQuestions = [...questions[currentCategory]]
          .sort(() => Math.random() - 0.5)
          .slice(0, 10);
        currentIndex = 0;
        score = 0;
        totalTime = 0;
        showScreen("quizScreen");
        showQuestion();
      }

      function showQuestion() {
        answered = false;
        const q = currentQuestions[currentIndex];
        document.getElementById("questionNum").textContent =
          `${currentIndex + 1}/${currentQuestions.length}`;
        document.getElementById("progressFill").style.width =
          `${((currentIndex + 1) / currentQuestions.length) * 100}%`;
        document.getElementById("question").textContent = q.q;

        const letters = ["A", "B", "C", "D"];
        document.getElementById("options").innerHTML = q.options
          .map(
            (opt, i) => `
                <div class="option" onclick="selectAnswer(${i})">
                    <span class="option-letter">${letters[i]}</span>
                    <span>${opt}</span>
                </div>
            `
          )
          .join("");

        document.getElementById("explanation").style.display = "none";
        document.getElementById("nextBtn").style.display = "none";

        timeLeft = currentDifficulty === "easy" ? 30 : currentDifficulty === "medium" ? 20 : 15;
        startTimer();
      }

      function startTimer() {
        clearInterval(timer);
        updateTimerDisplay();
        timer = setInterval(() => {
          timeLeft--;
          totalTime++;
          updateTimerDisplay();
          if (timeLeft <= 0) {
            clearInterval(timer);
            if (!answered) selectAnswer(-1);
          }
        }, 1000);
      }

      function updateTimerDisplay() {
        document.getElementById("timer").textContent = `⏱️ ${timeLeft}s`;
        document.getElementById("timer").style.color = timeLeft <= 5 ? "#f5576c" : "#666";
      }

      function selectAnswer(index) {
        if (answered) return;
        answered = true;
        clearInterval(timer);

        const q = currentQuestions[currentIndex];
        const options = document.querySelectorAll(".option");

        options.forEach((opt, i) => {
          opt.style.pointerEvents = "none";
          if (i === q.answer) {
            opt.classList.add("correct");
          } else if (i === index) {
            opt.classList.add("wrong");
          }
        });

        if (index === q.answer) {
          score++;
        }

        document.getElementById("explanation").textContent = q.explain;
        document.getElementById("explanation").style.display = "block";
        document.getElementById("nextBtn").style.display = "block";
        document.getElementById("nextBtn").textContent =
          currentIndex === currentQuestions.length - 1 ? "查看结果" : "下一题";
      }

      function nextQuestion() {
        currentIndex++;
        if (currentIndex >= currentQuestions.length) {
          showResults();
        } else {
          showQuestion();
        }
      }

      function showResults() {
        showScreen("resultScreen");
        const percentage = Math.round((score / currentQuestions.length) * 100);

        let icon = "🏆",
          text = "太棒了！";
        if (percentage < 60) {
          icon = "😅";
          text = "继续加油！";
        } else if (percentage < 80) {
          icon = "👍";
          text = "做得不错！";
        } else if (percentage < 100) {
          icon = "🎉";
          text = "非常优秀！";
        } else {
          icon = "🏆";
          text = "满分！完美！";
        }

        document.getElementById("resultIcon").textContent = icon;
        document.getElementById("resultScore").textContent = percentage + "%";
        document.getElementById("resultText").textContent = text;
        document.getElementById("correctCount").textContent = score;
        document.getElementById("wrongCount").textContent = currentQuestions.length - score;
        document.getElementById("avgTime").textContent =
          Math.round(totalTime / currentQuestions.length) + "s";
      }

      function restartQuiz() {
        showScreen("startScreen");
      }

      function showScreen(screenId) {
        document.querySelectorAll(".quiz-screen").forEach((s) => s.classList.remove("active"));
        document.getElementById(screenId).classList.add("active");
      }
    
